test('animation starts on an action and the lab recovers from a transport error', async ({ page }, testInfo) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/lessons/request')
  await page.route('**/api/simulate', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ statusMessage: 'Temporary lab failure' }) }))
  await page.getByRole('button', { name: 'Load collection' }).click()
  await expect(page.getByRole('alert')).toContainText('Temporary lab failure')
  await page.unroute('**/api/simulate')
  await page.getByRole('button', { name: 'Load collection' }).click()
  if (testInfo.project.name === 'mobile') await page.getByRole('tab', { name: 'Architecture', exact: true }).click()
  await expect(page.locator('.request-packet')).toBeVisible()
  await finishFlow(page)
  if (testInfo.project.name === 'mobile') await page.getByRole('tab', { name: 'Product', exact: true }).click()
  await expect(page.locator('.product-outcome')).toContainText('Your collection is ready')
})

test('simulation API rejects unknown lessons, malformed state, unsafe URLs and incompatible actions', async ({ request }) => {
  const send = (data: unknown) => request.post('/api/simulate', { data })
  expect((await send({ lessonId: 'unknown', action: 'load', scenario: 'normal' })).status()).toBe(404)
  expect((await send({ lessonId: 'request', action: 'pay', scenario: 'normal' })).status()).toBe(400)
  expect((await send({ lessonId: 'request', action: 'load', scenario: 'normal', state: {} })).status()).toBe(400)
  expect((await send({ lessonId: 'shortener', action: 'shorten', scenario: 'normal', url: 'javascript:alert(1)' })).status()).toBe(400)
  expect((await send({ lessonId: 'request', action: 'load', scenario: 'normal', extra: 'x'.repeat(33000) })).status()).toBe(413)
  const normal = await send({ lessonId: 'request', action: 'load', scenario: 'normal' })
  expect(normal.status()).toBe(200)
  expect(normal.headers()['cache-control']).toBe('no-store')
  expect((await normal.json()).result.title).toBe('Your collection is ready')
})
