import { test, expect } from '@playwright/test'
import type { APIRequestContext, Page } from '@playwright/test'
import type { Lesson } from '../../shared/types'

test.use({ reducedMotion: 'reduce' })

async function visit(page: Page, request: APIRequestContext, id: string) {
  const lessons: Lesson[] = await (await request.get('/api/lessons')).json()
  const ids = lessons.slice(0, lessons.findIndex(item => item.id === id)).map(item => item.id)
  await page.addInitScript((completed) => localStorage.setItem('systems-atlas:progress:v1', JSON.stringify({ version: 1, started: completed, completed })), ids)
  await page.goto(`/lessons/${id}`)
  await expect(page.getByRole('heading', { name: 'A real interaction. A visible system.' })).toBeVisible()
}
async function finishFlow(page: Page) {
  await expect(page.locator('.simulation-lab')).toHaveAttribute('aria-busy', 'false')
  await expect(page.locator('.event-list')).toBeVisible()
  await page.locator('.event-list button').last().click()
}

